#!/usr/bin/env python3
"""Print services.slop-dn42.peers (Nix) for the peers dn42ctl configured on the Arch host.

Reads /etc/systemd/network/30-dn_*.{netdev,network} and /etc/bird/peers/*.conf
(public data only; the private key stays in /etc/wireguard/dn42.key).
Usage: scripts/dn42-peers-from-arch.py > config/services/dn42/peers.nix
"""
import glob
import os
import re
import sys

NETWORK_DIR = "/etc/systemd/network"
BIRD_PEERS_DIR = "/etc/bird/peers"
DEFAULT_LOCAL = "fe80::125/64"


def entries(path):
    """(section, key, value) triples of a systemd unit file."""
    section = None
    for line in open(path):
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            section = line[1:-1]
        elif "=" in line and not line.startswith("#"):
            key, value = line.split("=", 1)
            yield section, key, value


def nix_str(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${") + '"'


def main():
    peers = {}
    for conf in sorted(glob.glob(os.path.join(BIRD_PEERS_DIR, "*.conf"))):
        name = os.path.basename(conf)[:-len(".conf")]
        text = open(conf).read()
        neighbor = re.search(r"neighbor\s+(\S+)\s+as\s+(\d+);", text)
        iface = re.search(r'interface\s+"([^"]+)";', text)
        if not neighbor or not iface:
            sys.exit(f"{conf}: no neighbor/interface")
        peers[name] = {"neighbor": neighbor.group(1), "asn": int(neighbor.group(2)), "interface": iface.group(1)}

    out = ["# Generated by scripts/dn42-peers-from-arch.py from the Arch host's dn42ctl files.",
           "# Public keys and addresses only; the private key is /etc/wireguard/dn42.key.",
           "{"]
    for name, peer in peers.items():
        iface = peer["interface"]
        netdev = list(entries(os.path.join(NETWORK_DIR, f"30-{iface}.netdev")))
        network = list(entries(os.path.join(NETWORK_DIR, f"30-{iface}.network")))
        get = lambda unit, key: [v for s, k, v in unit if k == key]
        addresses = get(network, "Address")
        local = [a for a in addresses if a.startswith("fe80")]
        extra_addresses = [a for a in addresses if not a.startswith("fe80")]
        routes = [d for d in get(network, "Destination") if d != peer["neighbor"]]
        if len(local) != 1 or peer["neighbor"] not in get(network, "Destination"):
            sys.exit(f"{iface}: unexpected addresses/routes")
        out.append(f"  {nix_str(name)} = {{")
        out.append(f"    asn = {peer['asn']};")
        out.append(f"    publicKey = {nix_str(get(netdev, 'PublicKey')[0])};")
        if get(netdev, "Endpoint"):
            out.append(f"    endpoint = {nix_str(get(netdev, 'Endpoint')[0])};")
        out.append(f"    listenPort = {get(netdev, 'ListenPort')[0]};")
        out.append(f"    neighbor = {nix_str(peer['neighbor'])};")
        if iface != "dn_" + name[:12]:
            out.append(f"    interface = {nix_str(iface)};")
        if local[0] != DEFAULT_LOCAL:
            out.append(f"    localAddress = {nix_str(local[0])};")
        if extra_addresses:
            out.append(f"    extraAddresses = [ {' '.join(map(nix_str, extra_addresses))} ];")
        if routes:
            out.append(f"    extraRoutes = [ {' '.join(map(nix_str, routes))} ];")
        out.append("  };")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
